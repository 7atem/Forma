"""Generate matching Kotlin/Swift exercise maps and Android labels from one source.

Run with --check in CI. Geometry is original schematic art, not an EMG measurement.
"""
from pathlib import Path
import json
import math
import sys
import xml.etree.ElementTree as ET


def android_text(text):
    """Escape aapt2 string syntax; ElementTree already escapes XML entities."""
    text = text.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')
    return '\\' + text if text[:1] in ('@', '?') else text


ROOT =Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'catalog/exercise-muscles.json').read_text(encoding='utf-8'))
quote = lambda text: json.dumps(text, ensure_ascii=False)
muscles = data['muscles']
exercises = data['exercises']
ids = {item['id'] for item in muscles}
assert len(ids) == len(muscles)
assert len({item['id'] for item in exercises}) == len(exercises)
assert all(item['primary'] and not set(item['primary']) & set(item['secondary']) for item in exercises)
assert all(set(item['primary'] + item['secondary']) <= ids for item in exercises)
details = data['details']
detail_ids = [item['id'] for item in details]
group_of = {item['id']: item['group'] for item in details}
assert len(set(detail_ids)) == len(detail_ids)
assert set(group_of.values()) == ids, 'every broad group needs at least one detailed region'
assert {item['detail'] for item in data['regions']} == set(detail_ids)
assert all(item['view'] in {'front', 'back'} for item in data['regions'])
assert all(isinstance(item['fiber'], (int, float)) and 0 <= item['fiber'] < 360 for item in data['regions'])
for item in exercises:
    # Detailed regions must roll up exactly to the broad groups used for counts, filters and transfers.
    primary_detail, secondary_detail = item['primaryDetail'], item['secondaryDetail']
    assert primary_detail and not set(primary_detail) & set(secondary_detail), item['id']
    assert len(set(primary_detail)) == len(primary_detail) and len(set(secondary_detail)) == len(secondary_detail), item['id']
    assert {group_of[d] for d in primary_detail} == set(item['primary']), item['id']
    assert {group_of[d] for d in secondary_detail} - set(item['primary']) == set(item['secondary']), item['id']
for item in exercises:
    assert len(set(item['primary'])) == len(item['primary'])
    assert len(set(item['secondary'])) == len(item['secondary'])
for commands in [data['outline']] + [item['path'] for item in data['regions']]:
    tokens = commands.split()
    index = 0
    assert tokens[0] == 'M'
    while index < len(tokens):
        operation = tokens[index]
        assert operation in {'M', 'L', 'C', 'Z'}, operation
        count = {'M': 2, 'L': 2, 'C': 6, 'Z': 0}[operation]
        coordinates = [float(n) for n in tokens[index + 1:index + 1 + count]]
        assert len(coordinates) == count and all(math.isfinite(n) for n in coordinates)
        assert all(0 <= n <= (100 if i % 2 == 0 else 220) for i, n in enumerate(coordinates))
        index += count + 1

kt = '// Generated by scripts/generate_exercise_catalog.py; edit catalog/exercise-muscles.json.\n'
kt += 'package com.formacoach.model\n\n'
kt += 'enum class Exercise { ' + ', '.join(item['id'] for item in exercises) + ' }\n'
equipment=['BODYWEIGHT','DUMBBELLS','BARBELL','CABLE','MACHINE','BENCH','BOX','PULL_UP_BAR']
assert all(x.get('equipment') and set(x['equipment']) <= set(equipment) for x in exercises)
kt += 'enum class Equipment { '+', '.join(equipment)+' }\n'
kt += 'data class ExerciseDetails(val equipment:List<Equipment>,val perSide:Boolean)\n'
kt += 'object ExerciseCatalog {\n    fun of(exercise:Exercise):ExerciseDetails=when(exercise) {\n'
for x in exercises:
    kt += f'        Exercise.{x["id"]}->ExerciseDetails(listOf('+','.join('Equipment.'+e for e in x['equipment'])+f'),{str(x["perSide"]).lower()})\n'
kt += '    }\n    fun searchText(exercise:Exercise):String=when(exercise) {\n'
for x in exercises:kt += f'        Exercise.{x["id"]}->{quote(x["en"]+" "+x["ar"]+" "+x["id"].replace("_"," "))}\n'
kt += '    }\n    fun similar(exercise:Exercise):List<Exercise> = Exercise.entries.filter {it!=exercise && ExerciseMuscles.of(it).primary.any {muscle ->muscle in ExerciseMuscles.of(exercise).primary}}\n}\n'
kt += 'enum class Muscle { ' + ', '.join(item['id'] for item in muscles) + ' }\n'
kt += 'enum class MuscleDetail(val group: Muscle) { ' + ', '.join(f'{d["id"]}(Muscle.{d["group"]})' for d in details) + ' }\n'
kt += 'data class MuscleActivation(val primary: List<Muscle>, val secondary: List<Muscle>, val primaryDetail: List<MuscleDetail>, val secondaryDetail: List<MuscleDetail>, val reference: String)\n'
kt += '/** One side of one detailed region; [fiber] is the drawn fibre direction in degrees (schematic, not measured anatomy). */\n'
kt += 'data class MuscleRegion(val detail: MuscleDetail, val front: Boolean, val fiber: Float, val path: String) { val muscle: Muscle get() = detail.group }\n'
kt += 'object ExerciseMuscles {\n    const val CATALOG_VERSION = 1\n'
kt += '    val outline = ' + quote(data['outline']) + '\n'
kt += '    val regions = listOf(\n'
for item in data['regions']:
    kt += f'        MuscleRegion(MuscleDetail.{item["detail"]}, {str(item["view"] == "front").lower()}, {item["fiber"]}f, {quote(item["path"])}),\n'
kt += '    )\n    fun of(exercise: Exercise): MuscleActivation = when(exercise) {\n'
for item in exercises:
    primary = ', '.join('Muscle.' + name for name in item['primary'])
    secondary = ', '.join('Muscle.' + name for name in item['secondary'])
    primary_detail = ', '.join('MuscleDetail.' + name for name in item['primaryDetail'])
    secondary_detail = ', '.join('MuscleDetail.' + name for name in item['secondaryDetail'])
    kt += f'        Exercise.{item["id"]} -> MuscleActivation(listOf({primary}), listOf({secondary}), listOf({primary_detail}), listOf({secondary_detail}), {quote(item["reference"])} )\n'
kt += '    }\n}\n'

swift = '// Generated by scripts/generate_exercise_catalog.py. Original Forma schematic art.\nimport Foundation\n\n'
swift += 'public enum Exercise: String, Codable, CaseIterable, Sendable {\n'
for item in exercises:
    swift += f'    case {item["id"].lower()} = {quote(item["id"])}\n'
swift += '    public func label(arabic: Bool) -> String {\n        switch self {\n'
for item in exercises:
    swift += f'        case .{item["id"].lower()}: return arabic ? {quote(item["ar"])} : {quote(item["en"])}\n'
swift += '        }\n    }\n}\n'
swift += 'public enum Equipment: String, Codable, CaseIterable, Sendable {\n'
equipment_labels=[('Bodyweight','وزن الجسم'),('Dumbbells','دمبل'),('Barbell','بار'),('Cable','كابل'),('Machine','جهاز'),('Bench','مقعد'),('Box / step','صندوق / درجة'),('Pull-up bar','عارضة عقلة')]
for e in equipment:swift += f'    case {e.lower()} = {quote(e)}\n'
swift += '    public func label(arabic:Bool)->String {switch self {\n'
for e,(en,ar) in zip(equipment,equipment_labels):swift += f'        case .{e.lower()}:return arabic ? {quote(ar)} : {quote(en)}\n'
swift += '    }}\n}\npublic struct ExerciseDetails:Sendable {public let equipment:[Equipment];public let perSide:Bool}\n'
swift += 'public enum ExerciseCatalog {public static func of(_ exercise:Exercise)->ExerciseDetails {switch exercise {\n'
for x in exercises:swift += f'    case .{x["id"].lower()}:return .init(equipment:['+','.join('.'+e.lower() for e in x['equipment'])+f'],perSide:{str(x["perSide"]).lower()})\n'
swift += '}}}\n'
swift += 'public enum Muscle: String, Codable, CaseIterable, Sendable {\n'
for item in muscles:
    swift += f'    case {item["id"].lower()} = {quote(item["id"])}\n'
swift += '    public func label(arabic: Bool) -> String {\n        switch self {\n'
for item in muscles:
    swift += f'        case .{item["id"].lower()}: return arabic ? {quote(item["ar"])} : {quote(item["en"])}\n'
swift += '        }\n    }\n}\n'
swift += 'public enum MuscleDetail: String, Codable, CaseIterable, Sendable {\n'
for item in details:
    swift += f'    case {item["id"].lower()} = {quote(item["id"])}\n'
swift += '    public var group: Muscle {\n        switch self {\n'
for item in details:
    swift += f'        case .{item["id"].lower()}: return .{item["group"].lower()}\n'
swift += '        }\n    }\n    public func label(arabic: Bool) -> String {\n        switch self {\n'
for item in details:
    swift += f'        case .{item["id"].lower()}: return arabic ? {quote(item["ar"])} : {quote(item["en"])}\n'
swift += '        }\n    }\n}\n'
swift += 'public struct MuscleRegion: Sendable { public let detail: MuscleDetail; public let front: Bool; public let fiber: Double; public let path: String; public var muscle: Muscle { detail.group } }\n'
swift += 'public struct MuscleActivation: Sendable { public let primary: [Muscle]; public let secondary: [Muscle]; public let primaryDetail: [MuscleDetail]; public let secondaryDetail: [MuscleDetail]; public let reference: String }\n'
swift += 'public enum ExerciseMuscles {\n    public static let version = 1\n    public static let outline = ' + quote(data['outline']) + '\n'
swift += '    public static let regions: [MuscleRegion] = [\n'
for item in data['regions']:
    swift += f'        .init(detail: .{item["detail"].lower()}, front: {str(item["view"] == "front").lower()}, fiber: {item["fiber"]}, path: {quote(item["path"])}),\n'
swift += '    ]\n    public static func of(_ exercise: Exercise) -> MuscleActivation {\n        switch exercise {\n'
for item in exercises:
    primary = ', '.join('.' + name.lower() for name in item['primary'])
    secondary = ', '.join('.' + name.lower() for name in item['secondary'])
    primary_detail = ', '.join('.' + name.lower() for name in item['primaryDetail'])
    secondary_detail = ', '.join('.' + name.lower() for name in item['secondaryDetail'])
    swift += f'        case .{item["id"].lower()}: return .init(primary: [{primary}], secondary: [{secondary}], primaryDetail: [{primary_detail}], secondaryDetail: [{secondary_detail}], reference: {quote(item["reference"])})\n'
swift += '        }\n    }\n}\n'

labels = 'package com.formacoach.app\n\nimport com.formacoach.model.Muscle\n\ninternal fun muscleLabel(muscle: Muscle): Int = when(muscle) {\n'
for item in muscles:
    labels += f'    Muscle.{item["id"]} -> R.string.muscle_{item["id"].lower()}\n'
labels += '}\n'
labels += '\ninternal fun muscleDetailLabel(detail: com.formacoach.model.MuscleDetail): Int = when(detail) {\n'
for item in details:
    labels += f'    com.formacoach.model.MuscleDetail.{item["id"]} -> R.string.muscle_detail_{item["id"].lower()}\n'
labels += '}\n'
labels += '\ninternal fun exerciseLabel(exercise:com.formacoach.model.Exercise):Int=when(exercise) {\n'
for x in exercises:labels += f'    com.formacoach.model.Exercise.{x["id"]}->R.string.catalog_exercise_{x["id"].lower()}\n'
labels += '}\n'
labels += '\ninternal fun equipmentLabel(value:com.formacoach.model.Equipment):Int=when(value) {\n'
for x in equipment:labels += f'    com.formacoach.model.Equipment.{x}->R.string.equipment_{x.lower()}\n'
labels += '}\n'
outputs = {
    ROOT/'core/model/src/main/kotlin/com/formacoach/model/ExerciseMuscles.Generated.kt': kt,
    ROOT/'app/src/main/kotlin/com/formacoach/app/MuscleLabels.Generated.kt': labels,
    ROOT/'apple/Sources/FormaCore/ExerciseCatalog.Generated.swift': swift,
}
for folder, language in [('values', 'en'), ('values-ar', 'ar')]:
    resources = ET.Element('resources')
    for item in muscles:
        ET.SubElement(resources, 'string', name='muscle_' + item['id'].lower()).text = android_text(item[language])
    for item in details:
        ET.SubElement(resources, 'string', name='muscle_detail_' + item['id'].lower()).text = android_text(item[language])
    for item in exercises:
        ET.SubElement(resources,'string',name='catalog_exercise_'+item['id'].lower()).text=android_text(item[language])
    ET.indent(resources, space='    ')
    outputs[ROOT/f'app/src/main/res/{folder}/muscles.xml'] = '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(resources, encoding='unicode') + '\n'
for path, content in outputs.items():
    if '--check' in sys.argv:
        assert path.is_file() and path.read_text(encoding='utf-8') == content, str(path)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')
print(f'{len(exercises)} exercises, {len(muscles)} muscle groups, {len(details)} detailed regions; Kotlin/Swift/resources synchronized.')
