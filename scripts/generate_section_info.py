"""Generate bilingual section info-button text for Android and Swift from catalog/section-info.json.

Each topic explains one screen section in three short parts: what it shows, how it works, and what is good to know.
Text describes app behaviour only; it never advises intake, training or health decisions.
"""
from pathlib import Path
import json
import re
import sys
import xml.etree.ElementTree as ET


def android_text(text):
    """Escape aapt2 string syntax; ElementTree already escapes XML entities."""
    text = text.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')
    return '\\' + text if text[:1] in ('@', '?') else text


def camel(value):
    head, *rest = value.split('_')
    return head + ''.join(part.capitalize() for part in rest)


root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'catalog/section-info.json').read_text(encoding='utf-8'))
labels, topics = data['labels'], data['topics']
PARTS = ('title', 'what', 'how', 'note')
PLATFORMS = {'android', 'apple'}
ids = [topic['id'] for topic in topics]
assert len(ids) == len(set(ids)), 'duplicate topic id'
assert set(labels) == {'about', 'what', 'how', 'note', 'close', 'more'}
for topic in topics:
    assert re.fullmatch(r'[a-z][a-z0-9_]*', topic['id']), topic['id']
    assert set(topic.get('platforms', PLATFORMS)) <= PLATFORMS, topic['id']
    for part in PARTS:
        for lang in ('en', 'ar'):
            text = topic[part][lang].strip()
            assert text and text == topic[part][lang], (topic['id'], part, lang)
            # Literal percent signs need escaping on Android and in Swift format strings; keep them out.
            assert '%' not in text, (topic['id'], part, lang)
for key, value in labels.items():
    assert (value['en'].count('%1$s'), value['ar'].count('%1$s')) == ((1, 1) if key == 'about' else (0, 0)), key

android_topics = [t for t in topics if 'android' in t.get('platforms', PLATFORMS)]
apple_topics = [t for t in topics if 'apple' in t.get('platforms', PLATFORMS)]
quote = lambda text: json.dumps(text, ensure_ascii=False)
header = 'Generated by scripts/generate_section_info.py from catalog/section-info.json. Do not edit.'

kt = f'// {header}\npackage com.formacoach.app\n\n'
kt += '/** Section explanations shown by [SectionInfoButton]: title, what it shows, how it works and good to know. */\n'
kt += 'internal enum class InfoTopic(val title: Int, val what: Int, val how: Int, val note: Int) {\n'
for topic in android_topics:
    key = topic['id']
    kt += f'    {key.upper()}(' + ', '.join(f'R.string.info_{key}_{part}' for part in PARTS) + '),\n'
kt += '}\n'

swift = f'// {header}\nimport Foundation\n\n'
swift += 'public struct SectionInfoText: Sendable, Equatable {\n'
swift += '    public let title: String\n    public let what: String\n    public let how: String\n    public let note: String\n}\n\n'
swift += 'public struct SectionInfoLabels: Sendable, Equatable {\n'
swift += '    /// Accessibility label format with one `%@` for the section title.\n'
swift += '    public let aboutFormat: String\n    public let what: String\n    public let how: String\n    public let note: String\n    public let close: String\n    public let more: String\n}\n\n'
swift += '/// Section explanations shown by the iPhone info button: title, what it shows, how it works and good to know.\n'
swift += 'public enum InfoTopic: String, CaseIterable, Sendable {\n'
for topic in apple_topics:
    swift += f'    case {camel(topic["id"])} = {quote(topic["id"])}\n'
swift += '}\n\npublic enum SectionInfo {\n'
swift_label = lambda lang: 'SectionInfoLabels(' + ', '.join(
    f'{"aboutFormat" if key == "about" else key}: {quote(labels[key][lang].replace("%1$s", "%@"))}'
    for key in ('about', 'what', 'how', 'note', 'close', 'more')) + ')'
swift += f'    public static func labels(arabic: Bool) -> SectionInfoLabels {{\n        arabic ? {swift_label("ar")} : {swift_label("en")}\n    }}\n\n'
swift += '    public static func of(_ topic: InfoTopic, arabic: Bool) -> SectionInfoText {\n        switch topic {\n'
for topic in apple_topics:
    text = lambda lang: 'SectionInfoText(' + ', '.join(f'{part}: {quote(topic[part][lang])}' for part in PARTS) + ')'
    swift += f'        case .{camel(topic["id"])}:\n            return arabic ? {text("ar")} : {text("en")}\n'
swift += '        }\n    }\n}\n'

outputs = {
    root / 'app/src/main/kotlin/com/formacoach/app/SectionInfo.Generated.kt': kt,
    root / 'apple/Sources/FormaCore/SectionInfo.Generated.swift': swift,
}
for folder, lang in (('values', 'en'), ('values-ar', 'ar')):
    xml = ET.Element('resources')
    xml.append(ET.Comment(f' {header} '))
    for key in ('about', 'what', 'how', 'note', 'more'):
        ET.SubElement(xml, 'string', name=f'info_label_{key}').text = android_text(labels[key][lang])
    for topic in android_topics:
        for part in PARTS:
            ET.SubElement(xml, 'string', name=f'info_{topic["id"]}_{part}').text = android_text(topic[part][lang])
    ET.indent(xml, space='    ')
    outputs[root / f'app/src/main/res/{folder}/section_info.xml'] = '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(xml, encoding='unicode') + '\n'

for path, content in outputs.items():
    if '--check' in sys.argv:
        assert path.exists() and path.read_text(encoding='utf-8') == content, f'{path} is out of date; run scripts/generate_section_info.py'
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')
print(f'{len(topics)} bilingual section explanations synchronized ({len(android_topics)} Android, {len(apple_topics)} iPhone).')
