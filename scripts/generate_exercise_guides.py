"""Generate bilingual Android/Swift guides; illustrations are shared original assets."""
from pathlib import Path
import json
import sys
import xml.etree.ElementTree as ET


def android_text(text):
    """Escape aapt2 string syntax; ElementTree already escapes XML entities."""
    text = text.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')
    return '\\' + text if text[:1] in ('@', '?') else text


root =Path(__file__).resolve().parents[1]
data = json.loads((root/'catalog/exercise-guides.json').read_text(encoding='utf-8'))['exercises']
catalog = json.loads((root/'catalog/exercise-muscles.json').read_text(encoding='utf-8'))['exercises']
assert [x['id'] for x in data] == [x['id'] for x in catalog]
assert all(len(x['cues']['en']) == len(x['cues']['ar']) == 3 for x in data)
quote = lambda text: json.dumps(text, ensure_ascii=False)
kt = '// Generated by scripts/generate_exercise_guides.py.\npackage com.formacoach.app\n\nimport com.formacoach.model.Exercise\n\n'
kt += 'internal data class GuideResources(val image:Int,val variant:Int,val cues:List<Int>,val reference:String)\n'
kt += 'internal fun guideResources(exercise:Exercise):GuideResources=when(exercise) {\n'
swift = '// Generated by scripts/generate_exercise_guides.py.\nimport Foundation\n\n'
swift += 'public struct ExerciseGuide: Sendable {public let asset:String;public let variant:String;public let cues:[String];public let reference:String}\n'
swift += 'public enum ExerciseGuides {\n    public static func of(_ exercise:Exercise,arabic:Bool)->ExerciseGuide {\n        switch exercise {\n'
for x in data:
    key=x['id'].lower()
    kt += f'    Exercise.{x["id"]}->GuideResources(R.drawable.exercise_{key},R.string.guide_{key}_variant,listOf('+','.join(f'R.string.guide_{key}_{i}' for i in range(3))+f'),{quote(x["reference"])})\n'
    cues=lambda lang:'['+','.join(quote(c) for c in x['cues'][lang])+']'
    swift += f'        case .{key}:return .init(asset:"exercise_{key}",variant:arabic ? {quote(x["variant"]["ar"])} : {quote(x["variant"]["en"])},cues:arabic ? {cues("ar")} : {cues("en")},reference:{quote(x["reference"])})\n'
kt += '}\n';swift += '        }\n    }\n}\n'
outputs={root/'app/src/main/kotlin/com/formacoach/app/ExerciseGuides.Generated.kt':kt,root/'apple/Sources/FormaCore/ExerciseGuides.Generated.swift':swift}
for folder,lang in [('values','en'),('values-ar','ar')]:
    xml=ET.Element('resources')
    for x in data:
        key=x['id'].lower()
        ET.SubElement(xml,'string',name=f'guide_{key}_variant').text=android_text(x['variant'][lang])
        for i,cue in enumerate(x['cues'][lang]):ET.SubElement(xml,'string',name=f'guide_{key}_{i}').text=android_text(cue)
    ET.indent(xml,space='    ')
    outputs[root/f'app/src/main/res/{folder}/exercise_guides.xml']='<?xml version="1.0" encoding="utf-8"?>\n'+ET.tostring(xml,encoding='unicode')+'\n'
for path,content in outputs.items():
    if '--check' in sys.argv:assert path.read_text(encoding='utf-8')==content,str(path)
    else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content,encoding='utf-8')
print(f'{len(data)} bilingual exercise guides synchronized.')
